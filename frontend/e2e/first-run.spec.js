import { test, expect } from '@playwright/test'

test('empty installation creates its first Admin in the browser and then locks setup', async ({ page }) => {
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url())
    const response = await route.fetch({ url: `http://127.0.0.1:8766${url.pathname}${url.search}` })
    await route.fulfill({ response })
  })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Create Admin and enter' })).toBeVisible()
  await page.getByLabel('Admin full name').fill('Browser Setup Admin')
  await page.getByLabel('Email address').fill('setup@browser.test')
  await page.getByLabel('Password', { exact: true }).fill('chosen-test-password-123')
  await page.getByLabel('Confirm password').fill('different-test-password')
  await page.getByRole('button', { name: 'Create Admin and enter' }).click()
  await expect(page.getByRole('alert')).toContainText('Passwords do not match')
  await page.getByLabel('Confirm password').fill('chosen-test-password-123')
  await page.getByRole('button', { name: 'Create Admin and enter' }).click()
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  await page.getByRole('button', { name: 'Log out' }).click()
  await expect(page.getByRole('button', { name: 'Enter workspace' })).toBeVisible()
  await expect(page.getByLabel('Admin full name')).toHaveCount(0)
  await page.getByLabel('Email address').fill('setup@browser.test')
  await page.getByLabel('Password', { exact: true }).fill('chosen-test-password-123')
  await page.getByRole('button', { name: 'Enter workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Selected model evaluation' })).toBeVisible()
  await page.unrouteAll({ behavior: 'wait' })
})
