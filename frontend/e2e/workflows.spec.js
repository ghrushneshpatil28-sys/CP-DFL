test('admin queues a real secure aggregation experiment through the form', async ({ page }) => {
  await login(page, 'admin')
  await page.getByRole('link', { name: 'Federated learning', exact: true }).click()
  await page.getByRole('button', { name: 'Configure experiment' }).click()
  await page.getByLabel('Enable secure aggregation').check()
  await page.getByLabel('Training approach').selectOption('fedprox')
  await page.getByLabel('Rounds / centralized epochs').fill('1')
  await page.getByLabel('Input size').selectOption('64')
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/admin/federated/experiments') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Queue experiment', exact: true }).click()
  const response = await responsePromise
  expect(response.status()).toBe(201)
  const row = await response.json()
  expect(row.config.secure_aggregation).toBe(true)
  expect(row.config.algorithm).toBe('fedprox')
  await expect(page.getByText('SecAgg+ enabled / GroupNorm', { exact: false })).toBeVisible()
})

test('overview displays the selected model actual evaluated score', async ({ page }) => {
  await login(page, 'admin')
  const response = await page.request.get('/api/model/evaluation')
  expect(response.ok()).toBeTruthy()
  const evidence = await response.json()
  expect(evidence.status).toBe('verified')
  const correct = evidence.test.confusion_matrix.reduce((sum, row, i) => sum + row[i], 0)
  expect(evidence.test.accuracy).toBeCloseTo(correct / evidence.test.sample_count, 10)
  await expect(page.getByTestId('selected-model-accuracy')).toHaveText(`${(evidence.test.accuracy * 100).toFixed(1)}%`)
  await expect(page.getByRole('region', { name: 'Selected model evaluation' })).toContainText(evidence.model_version)
  await expect(page.getByRole('region', { name: 'Selected model evaluation' })).toContainText('not an individual patient')
})

