test('patient loading, request error and recovery states', async ({ page }) => {
  await login(page, 'doctor')
  let release
  const hold = new Promise(resolve => { release = resolve })
  await page.route('**/api/patients?**', async route => { await hold; await route.continue() })
  await page.goto('/#/patients')
  await expect(page.getByRole('status', { name: 'Loading' })).toBeVisible()
  release()
  await expect(page.getByLabel('Search patients')).toBeVisible()
  await page.unroute('**/api/patients?**')
  await page.route('**/api/patients?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Test-only service interruption' }) }))
  await page.getByLabel('Search patients').fill('interruption')
  await expect(page.getByRole('alert')).toContainText('Test-only service interruption')
  await page.unroute('**/api/patients?**')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
