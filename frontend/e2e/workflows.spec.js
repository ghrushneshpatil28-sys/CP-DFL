async function capture(page, name) {
  await page.evaluate(() => window.scrollTo({ top: 0, left: 0, behavior: 'instant' }))
  await page.screenshot({ path: `../docs/screens/${name}.png`, fullPage: true, animations: 'disabled' })
}

